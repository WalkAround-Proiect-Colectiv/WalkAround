CREATE TABLE countries (
    id BIGINT PRIMARY KEY,
    code VARCHAR(2) NOT NULL UNIQUE,
    name TEXT NOT NULL,
    continent VARCHAR(2) NOT NULL
);

CREATE TABLE municipalities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    country_id BIGINT NOT NULL REFERENCES countries(id),
    CONSTRAINT municipalities_country_name_unique UNIQUE (country_id, name),
    CONSTRAINT municipalities_id_country_unique UNIQUE (id, country_id)
);

CREATE TABLE airports (
    id BIGINT PRIMARY KEY,
    name TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    continent VARCHAR(2) NOT NULL,
    country_id BIGINT NOT NULL REFERENCES countries(id),
    municipality_id BIGINT,
    iata_code VARCHAR(3),
    CONSTRAINT airports_municipality_country_fk FOREIGN KEY (municipality_id, country_id)
        REFERENCES municipalities(id, country_id)
);

CREATE INDEX airports_country_id_idx ON airports(country_id);
CREATE INDEX airports_municipality_id_idx ON airports(municipality_id);
CREATE INDEX airports_iata_code_idx ON airports(iata_code) WHERE iata_code IS NOT NULL;
