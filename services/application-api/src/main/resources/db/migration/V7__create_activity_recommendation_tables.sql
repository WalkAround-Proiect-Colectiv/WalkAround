CREATE TABLE activity_category (
    code VARCHAR(64) PRIMARY KEY,
    display_name VARCHAR(120) NOT NULL,
    icon_key VARCHAR(64) NOT NULL,
    indoor BOOLEAN NOT NULL,
    osm_filter VARCHAR(255) NOT NULL
);

CREATE TABLE weather_activity_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weather_bucket VARCHAR(32) NOT NULL CHECK (weather_bucket IN ('CLEAR', 'CLOUDY', 'RAIN', 'STORM', 'SNOW', 'FOG')),
    temperature_band VARCHAR(16) CHECK (temperature_band IN ('COLD', 'MILD', 'HOT')),
    time_of_day VARCHAR(16) CHECK (time_of_day IN ('DAY', 'NIGHT')),
    activity_category VARCHAR(64) NOT NULL REFERENCES activity_category(code) ON DELETE CASCADE,
    weight INTEGER NOT NULL CHECK (weight > 0),
    indoor BOOLEAN NOT NULL
);

CREATE UNIQUE INDEX weather_activity_rule_unique_idx
    ON weather_activity_rule (
        weather_bucket,
        COALESCE(temperature_band, 'ANY'),
        COALESCE(time_of_day, 'ANY'),
        activity_category
    );

CREATE INDEX weather_activity_rule_bucket_idx
    ON weather_activity_rule (weather_bucket);

