CREATE TABLE emergency_numbers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code VARCHAR(2) NOT NULL REFERENCES countries(code),
    source VARCHAR(255) NOT NULL,
    source_record_id VARCHAR(100) NOT NULL,
    number_type VARCHAR(20) NOT NULL,
    number TEXT NOT NULL,
    is_general_emergency BOOLEAN NOT NULL DEFAULT FALSE,
    name TEXT,
    organization TEXT,
    category TEXT,
    last_verified DATE,
    verification_status TEXT,
    scope TEXT,
    geography TEXT,
    hours TEXT,
    cost TEXT,
    target TEXT,
    languages JSONB,
    website TEXT,
    chat_url TEXT,
    email TEXT,
    notes TEXT,
    source_links JSONB,
    dataset_version TEXT NOT NULL,
    CONSTRAINT emergency_numbers_type_check CHECK (number_type IN ('voice', 'sms', 'text', 'short_code')),
    CONSTRAINT emergency_numbers_country_code_check CHECK (country_code ~ '^[A-Z]{2}$'),
    CONSTRAINT emergency_numbers_unique UNIQUE (source, country_code, source_record_id, number_type, number)
);

CREATE INDEX emergency_numbers_country_code_idx ON emergency_numbers(country_code);
CREATE INDEX emergency_numbers_country_category_idx ON emergency_numbers(country_code, category);
